import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

const signup = await readFile("signup.html", "utf8");
const auth = await readFile("js/auth/auth.js", "utf8");
const access = await readFile("js/shared/access-control.js", "utf8");
const consent = await readFile("legal-consent.html", "utf8");
const terms = await readFile("terms.html", "utf8");
const privacy = await readFile("privacy.html", "utf8");
const migration = await readFile("supabase/migrations/20261025120000_add_versioned_legal_acceptances.sql", "utf8");
const protectedPages = [
  "coach-approvals.html",
  "coach-dashboard.html",
  "coach-exercises.html",
  "coach-leaderboards.html",
  "coach-member-detail.html",
  "coach-roster.html",
  "coach-testing.html",
  "coach-workouts.html",
  "member-dashboard.html",
  "member-goals.html",
  "member-habits.html",
  "member-history.html",
  "member-leaderboards.html",
  "member-training.html",
  "profile.html",
  "workout-session.html"
];

assert.match(signup, /id="signup-age-adult" name="signup-age-bracket" type="radio" value="18_or_older" required/, "signup offers the adult age confirmation");
assert.match(signup, /id="signup-age-minor" name="signup-age-bracket" type="radio" value="13_to_17" required/, "signup offers the minor-with-permission confirmation");
assert.match(signup, /id="signup-legal-confirmation"[^>]*required/, "signup requires the legal acknowledgment");
assert.match(signup, /data-clear-age-choice="signup-age-bracket"/, "signup age selection can be cleared after an accidental choice");
assert.match(signup, /href="terms\.html"/, "signup links to the Terms of Service");
assert.match(signup, /href="privacy\.html"/, "signup links to the Privacy Policy");
assert.match(auth, /rpc\("record_current_legal_acceptance"/, "signup and re-acceptance use the guarded database RPC");
assert.match(auth, /input\[name='signup-age-bracket'\]:checked/, "signup derives one mutually exclusive age bracket");
assert.match(auth, /guardianPermissionConfirmed = ageBracket === "13_to_17"/, "minor confirmation records guardian permission");
assert.match(access, /if \(!legalStatus\.accepted\)/, "protected pages require the current document pair");
assert.match(access, /legal-consent\.html\?next=/, "protected pages route stale acceptances to the consent page");
assert.match(consent, /name="legal-age-bracket" type="radio" value="18_or_older" required/, "re-acceptance offers the adult choice");
assert.match(consent, /name="legal-age-bracket" type="radio" value="13_to_17" required/, "re-acceptance offers the minor-with-permission choice");
assert.match(consent, /data-clear-age-choice="legal-age-bracket"/, "re-acceptance age selection can be cleared");
assert.match(consent, /class="auth-body legal-consent-body"/, "existing users receive the modal-style required review screen");
assert.match(auth, /function setupAgeChoiceReset\(\)/, "age choices share the reset behavior");
assert.match(consent, /id="legal-consent-logout"/, "blocked users can log out and change accounts");
assert.match(consent, /js\/auth\/auth\.js\?v=signup-legal-3/, "required-review page loads the current legal-auth controller");
assert.match(terms, /You must be at least 13 years old/, "Terms state the age requirement");
assert.match(privacy, /not intended for children under 13/, "Privacy Policy describes the under-13 rule");
assert.match(terms, /data-legal-document="terms" data-legal-version="2026-10-25"/, "Terms expose the published version");
assert.match(privacy, /data-legal-document="privacy" data-legal-version="2026-10-25"/, "Privacy Policy exposes the published version");
assert.match(migration, /create table public\.legal_documents/, "migration creates the versioned legal-document catalog");
assert.match(migration, /create table public\.legal_acceptances/, "migration creates durable acceptance evidence");
assert.match(migration, /unique \(user_id, terms_document_id, privacy_document_id\)/, "one acceptance is stored per user and document pair");
assert.match(migration, /accepted_at timestamptz not null default now\(\)/, "acceptance time is generated by the database");
assert.match(migration, /grant execute on function public\.record_current_legal_acceptance/, "authenticated users can use only the guarded acceptance path");

for (const file of protectedPages) {
  const html = await readFile(file, "utf8");
  assert.match(html, /js\/shared\/access-control\.js\?v=legal-acceptance-2/, `${file} loads the current acceptance-gated access controller`);
}

console.log("Signup legal acknowledgment tests passed");
